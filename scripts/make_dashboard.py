"""Generate the Grafana dashboard ConfigMap (gitops/workloads/demo-app/dashboard.yaml).
Grafana's sidecar loads any ConfigMap labeled grafana_dashboard=1."""
import json
from pathlib import Path

DS = {"type": "prometheus", "uid": "${datasource}"}
BASE = 'namespace="demo", path="/"'


def panel(pid, title, exprs, x, y, w=12, h=8, unit="short", kind="timeseries", legend=True):
    return {"id": pid, "type": kind, "title": title, "datasource": DS,
            "gridPos": {"x": x, "y": y, "w": w, "h": h},
            "fieldConfig": {"defaults": {"unit": unit}, "overrides": []},
            "options": {"legend": {"displayMode": "list", "placement": "bottom", "showLegend": legend}},
            "targets": [{"refId": chr(65 + i), "expr": e, "legendFormat": lf, "datasource": DS}
                        for i, (e, lf) in enumerate(exprs)]}


panels = [
    panel(1, "Requests per second, by version",
          [(f'sum by (version) (rate(demo_http_requests_total{{{BASE}}}[1m]))', "{{version}}")], 0, 0, unit="reqps"),
    panel(2, "Error rate, by version",
          [(f'sum by (version) (rate(demo_http_requests_total{{{BASE}, code=~"5.."}}[1m])) '
            f'/ sum by (version) (rate(demo_http_requests_total{{{BASE}}}[1m]))', "{{version}}")], 12, 0, unit="percentunit"),
    panel(3, "p95 latency, by version",
          [('histogram_quantile(0.95, sum by (le, version) (rate(demo_http_request_seconds_bucket{namespace="demo", path="/"}[1m])))',
            "{{version}}")], 0, 8, unit="s"),
    panel(4, "Pods serving, by release",
          [('count by (rollouts_pod_template_hash) (up{namespace="demo", job="demo-app"} == 1)', "{{rollouts_pod_template_hash}}")],
          12, 8),
    panel(5, "Alerts firing",
          [('ALERTS{namespace="demo", alertstate="firing"}', "{{alertname}}")], 0, 16, w=24, h=6),
]
dash = {
    "title": "Platform Lab: demo-app", "uid": "platform-lab-demo", "schemaVersion": 39, "version": 1,
    "refresh": "5s", "time": {"from": "now-30m", "to": "now"}, "tags": ["platform-lab"],
    "templating": {"list": [{"name": "datasource", "type": "datasource", "query": "prometheus",
                             "current": {"text": "Prometheus", "value": "prometheus"}}]},
    "panels": panels,
}
cm = f"""# Generated by scripts/make_dashboard.py; edit that file, not this one.
apiVersion: v1
kind: ConfigMap
metadata:
  name: demo-app-dashboard
  labels:
    grafana_dashboard: "1"
data:
  platform-lab.json: |
""" + "\n".join("    " + line for line in json.dumps(dash, indent=2).splitlines()) + "\n"
out = Path(__file__).resolve().parent.parent / "gitops/workloads/demo-app/dashboard.yaml"
out.write_text(cm)
print("wrote", out)
